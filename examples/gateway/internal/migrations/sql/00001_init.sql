-- Collapsed baseline — the boilerplate was never deployed, so the original
-- incremental chain was merged into one authoritative migration. DO NOT
-- re-collapse a live schema: a deployed database has already applied the prior
-- chain.
--
-- This baseline merges the original 7-file chain:
--   00001 orders_read + inbox
--   00002 orders_read.created_at + keyset index
--   00003 audit_log + action/actor indexes
--   00004 audit_log append-only ownership transfer (preserved verbatim, last)
--   00005 audit_log hash-chain columns + audit_chain_head genesis
--   00006 audit_log chain_id + chain index, audit_chain_head singleton dropped
--   00007 product_views
-- The hash-chain columns (00005) and chain_id (00006) are folded into the
-- audit_log create table — the table is app-owned until the ownership-transfer
-- do-block (00004) runs LAST on the final-shape table. audit_chain_head is
-- created with the genesis seed and WITHOUT the singleton check (the chain ends
-- up sharded; the old chain added then dropped the singleton). The schema-diff
-- oracle (scripts/migoracle) proves this is byte-identical to the old chain.

-- +goose Up
create table orders_read (
    order_id     uuid        primary key,
    customer_id  text        not null,
    amount_cents bigint      not null,
    currency     text        not null,
    status       text        not null,
    updated_at   timestamptz not null default now(),
    -- created_at backs the keyset pagination cursor of GET /v1/orders
    -- (ordered by (created_at, order_id) descending).
    created_at   timestamptz not null default now()
);
create index orders_read_created_at_idx on orders_read (created_at desc, order_id desc);

create table inbox (
    consumer     text        not null,
    message_id   text        not null,
    processed_at timestamptz not null default now(),
    primary key (consumer, message_id)
);

-- Audit trail (platform/security/audit schema): the gateway serves the
-- admin-only DSAR read endpoint GET /v1/audit over this table. Same DDL as
-- the other services' audit_log so audit.PgStore works unchanged; the
-- (actor, created_at) index backs the by-actor read path (QueryByActor).
--
-- The hash-chain columns (prev_hash, entry_hash) and chain_id are folded in
-- here: audit.Record / audit.VerifyChain use them for tamper-evidence, and
-- chain_id default 1 (sharded chains, ADR-0018) keeps every write on the
-- single global chain (head id=1) until AUDIT_CHAIN_SHARDS > 1.
create table audit_log (
    id          bigint generated by default as identity primary key,
    actor       text        not null,
    action      text        not null,
    subject     text        not null,
    metadata    jsonb       not null default '{}'::jsonb,
    created_at  timestamptz not null default now(),
    prev_hash   bytea,
    entry_hash  bytea,
    chain_id    smallint    not null default 1
);
create index audit_log_action_idx on audit_log (action, created_at);
create index audit_log_actor_idx on audit_log (actor, created_at);
create index audit_log_chain_idx on audit_log (chain_id, id);

create table audit_chain_head (
    id         smallint primary key default 1,
    last_hash  bytea       not null,
    updated_at timestamptz not null default now()
);

