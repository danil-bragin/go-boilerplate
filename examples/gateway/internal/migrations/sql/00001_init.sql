-- app reads + advances (and lazily inserts sharded — ADR-0018) chain-head rows;
-- grant to the DATABASE OWNER (runtime app role) so it works under a privileged/
-- superuser migrate role (PG_MIGRATE_URL) too, not just migrate-as-app.
-- +goose StatementBegin
do $$
declare
    app_role text := (select pg_catalog.pg_get_userbyid(datdba)
                      from pg_database where datname = current_database());
begin
    execute format('grant select, insert, update on audit_chain_head to %I', app_role);
end
$$;
-- +goose StatementEnd

-- High-volume, low-value demo write (A2): one INSERT, NO outbox — so the
-- RecordProductView command can run with ConsistencyPolicy Eventual +
-- Transactional:false (no wrapping tx, async best-effort audit). Contrast with
-- the order flow, which is Strong/effectively-once via the Kafka outbox.
create table product_views (
    id          bigserial   primary key,
    product_id  text        not null,
    viewer      text        not null,
    viewed_at   timestamptz not null default now()
);

-- Append-only audit_log for the gateway (mirrors the platform audit migration
-- 00003_audit_append_only): the app role may INSERT + SELECT but never
-- UPDATE/DELETE. See deploy/postgres/init.sql for the role split and the
-- privileged retention path (PG_AUDIT_ADMIN_URL / audit_admin).
--
-- The gateway's audit_log is identity-based (bigint generated by default as
-- identity), so there is no separate sequence to grant — the identity sequence
-- is owned by the column and INSERT alone covers it.
--
-- OWNERSHIP IS LOAD-BEARING: an OWNER keeps UPDATE/DELETE implicitly, so unless
-- the table is owned by a NON-app role the REVOKE is a no-op. When audit_admin
-- exists (deploy/postgres/init.sql), transfer ownership to it and re-grant the
-- app role only INSERT + SELECT so the REVOKE actually denies the app's
-- UPDATE/DELETE. Skipped (best-effort) where audit_admin is absent — see the
-- platform audit migration 00003 for the full rationale and trade-off.
--
-- This do-block runs LAST, after audit_log already has its final shape
-- (hash-chain columns + chain_id), so the per-ALTER SET-ROLE dance of the old
-- chain is unnecessary — the transfer is the only owner-sensitive step.
-- +goose StatementBegin
-- Grant/revoke against the DATABASE OWNER (the runtime app role), not
-- current_user, so this works whether migrations run as app or a privileged/
-- superuser migrate role (PG_MIGRATE_URL). See platform audit 00003.
do $$
declare
    app_role text := (select pg_catalog.pg_get_userbyid(datdba)
                      from pg_database where datname = current_database());
begin
    if exists (select 1 from pg_roles where rolname = 'audit_admin') then
        execute 'alter table audit_log owner to audit_admin';
        -- Act AS the new owner — app is a non-owner after the transfer.
        set local role audit_admin;
        execute format('grant select, insert on audit_log to %I', app_role);
        execute format('revoke update, delete on audit_log from %I', app_role);
        reset role;
    else
        execute format('revoke update, delete on audit_log from %I', app_role);
    end if;
end
$$;
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
do $$
begin
    if exists (select 1 from pg_roles where rolname = 'audit_admin') then
        execute 'alter table audit_log owner to ' || quote_ident(current_user);
    end if;
    execute format('grant update, delete on audit_log to %I', current_user);
end
$$;
-- +goose StatementEnd
